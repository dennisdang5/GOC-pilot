"""Copy the labeling app + ID-only assignments into the separate labeling-kit repo.

Run from anywhere:  python -m src.labeling.export_kit <path-to-labeling-repo-clone>

This repo stays the single source for the app code; re-run after any change and push the kit.
Writes code, README, .gitignore, requirements and assignments/*.csv (ROW_ID, CATEGORY, n_chars,
label_order -- IDs only, no note text). Never touches files in the kit's labels/ folder.
Prints file names only.
"""

import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
ASSIGN_SRC = ROOT / "data" / "assignments"

CODE = [
    "src/__init__.py",
    "src/ingest/__init__.py",
    "src/ingest/load.py",
    "src/labeling/__init__.py",
    "src/labeling/app.py",
    "src/labeling/derive.py",
    "src/labeling/schema.py",
    ".streamlit/config.toml",
]

GITIGNORE = """\
# MIMIC-III data: never committed (PhysioNet DUA). Each labeler uses their own download.
data/**
!data/**/
!data/**/.gitkeep
*.parquet
*.csv
*.csv.gz
!assignments/*.csv

.venv/
__pycache__/
*.py[cod]
.idea/
"""

REQUIREMENTS = "duckdb\npandas\npyarrow\npydantic>=2\nstreamlit\n"


def readme() -> str:
    guide = (ROOT / "docs" / "labeling.md").read_text(encoding="utf-8")
    guide = guide.replace("Clone the private repo and install (Python 3.11+):\n"
                          "   `python -m pip install duckdb pandas pyarrow pydantic streamlit`.",
                          "Clone this repo and install (Python 3.11+):\n"
                          "   `python -m pip install -r requirements.txt`.")
    guide = guide.replace("3. Put the assignment file you were sent (e.g. `dev_B.parquet` or "
                          "`test_physician.parquet`) in\n   `data/assignments/`. It contains IDs only.",
                          "3. Your assignment is already in `assignments/` (IDs only): the physician "
                          "uses\n   `test_physician`; members use their `dev_` letter.")
    guide = guide.replace(
        "When you're done, share `data/labels/<assignment>_<INITIALS>.jsonl` with the team.",
        "Commit and push **only your own** `labels/<assignment>_<INITIALS>.jsonl` "
        "(`git add labels/<your file>`).\nDon't open other people's label files.")
    return ("<!-- Generated by src/labeling/export_kit.py in the main project repo. "
            "Don't edit here. -->\n" + guide)


def export(dest: Path, assign_src: Path = ASSIGN_SRC) -> list[str]:
    written = []
    for rel in CODE:
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        src = ROOT / rel
        if src.exists():
            shutil.copyfile(src, target)
        else:  # empty package marker
            target.write_text("", encoding="utf-8")
        written.append(rel)
    for rel, text in {"README.md": readme(), ".gitignore": GITIGNORE,
                      "requirements.txt": REQUIREMENTS,
                      ".labeling-kit": "Marker: app reads assignments/ and writes labels/.\n"}.items():
        (dest / rel).write_text(text, encoding="utf-8")
        written.append(rel)
    for rel in ["labels/.gitkeep", "data/raw/noteevents/.gitkeep"]:
        (dest / rel).parent.mkdir(parents=True, exist_ok=True)
        (dest / rel).touch()
        written.append(rel)
    (dest / "assignments").mkdir(exist_ok=True)
    for p in sorted(assign_src.glob("*.parquet")):
        df = pd.read_parquet(p)[["ROW_ID", "CATEGORY", "n_chars", "label_order"]]
        df.to_csv(dest / "assignments" / f"{p.stem}.csv", index=False)
        written.append(f"assignments/{p.stem}.csv")
    return written


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: python -m src.labeling.export_kit <path-to-labeling-repo-clone>")
        return 1
    dest = Path(sys.argv[1]).resolve()
    if not dest.is_dir() or not (dest / ".git").exists():
        print(f"export_kit: {dest} is not a git clone")
        return 1
    if dest == ROOT or ROOT in dest.parents:
        print("export_kit: destination must be outside the main repo")
        return 1
    for rel in export(dest):
        print(f"  {rel}")
    print(f"\nexported to {dest}. Review with `git status` there, then commit and push.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
